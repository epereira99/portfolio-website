// Generates src/journey/voyage/europe.ts: a projected Europe coastline and the voyage route.
// Data: Natural Earth 1:50m land via world-atlas (public domain).
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoConicConformal, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-50m.json"), "utf8"));
const land = feature(topo, topo.objects.land);

// Fit on the edges of the lon/lat box (a MultiPoint avoids polygon winding issues).
const edge = [];
for (let lon = -12; lon <= 25; lon += 1) edge.push([lon, 35], [lon, 63]);
for (let lat = 35; lat <= 63; lat += 1) edge.push([-12, lat], [25, lat]);

const projection = geoConicConformal()
  .parallels([40, 58])
  .rotate([-7, 0])
  .fitExtent([[40, 40], [960, 960]], { type: "MultiPoint", coordinates: edge })
  .clipExtent([[0, 0], [1000, 1000]]);

const round = ([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10];
const PORTO = [-8.61, 41.15];
const JONKOPING = [14.16, 57.78];
// Stylized sea route (spec §6): coast, Biscay, Channel, North Sea, Skagerrak, Gothenburg, overland.
const ROUTE = [PORTO, [-10.2, 43.6], [-6.5, 47.5], [-5.5, 49.3], [0.5, 50.3], [4.0, 53.5], [8.5, 57.9], [11.8, 57.7], JONKOPING];

const landPath = geoPath(projection).digits(1)(land);
const out = `// Generated by \`npm run gen:map\` (tools/map/make-europe.mjs). Do not edit by hand.
export const VIEWBOX = { w: 1000, h: 1000 };
export const PORTO: [number, number] = ${JSON.stringify(round(projection(PORTO)))};
export const JONKOPING: [number, number] = ${JSON.stringify(round(projection(JONKOPING)))};
export const ROUTE: [number, number][] = ${JSON.stringify(ROUTE.map((p) => round(projection(p))))};
export const LAND_PATH = ${JSON.stringify(landPath)};
`;
writeFileSync(new URL("../../src/journey/voyage/europe.ts", import.meta.url), out);
console.log(`wrote europe.ts (${(out.length / 1024).toFixed(1)} KB)`);
